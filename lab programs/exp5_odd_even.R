# EXPERIMENT-5
# ODD OR EVEN
#
# AIM: To write the program for odd or even using R-tool.

num <- as.integer(readline(prompt = "Enter a number: "))

if ((num %% 2) == 0) {
  print("Number is even")
} else {
  print("Number is odd")
}

# RESULT: Thus the basic program for odd or even is executed successfully.
