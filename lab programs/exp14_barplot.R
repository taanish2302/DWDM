# EXPERIMENT-14
# BAR PLOT AND HORIZONTAL BAR
#
# AIM: To draw the bar plot and horizontal bar using R-tool.

a <- c(55, 67, 89, 80, 90)

# Vertical bar plot
barplot(a, main = "Bar Plot")

# Horizontal bar plot
barplot(a, horiz = TRUE, main = "Horizontal Bar Plot")

# RESULT: Thus the bar and horizontal bar plot is executed successfully.
